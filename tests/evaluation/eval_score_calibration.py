"""
Evaluation — Score Calibration.

Citation/entailment checks (eval_hallucination.py) verify the LLM isn't
fabricating grounding — they say nothing about whether the *numeric score*
it assigns is actually correct. A gap analysis could cite real passages
perfectly and still score a clearly-excellent document as 30/100, or a
clearly-vague document as 90/100. This eval catches that: it feeds hand
-written "strong" (specific, evidenced) and "weak" (vague, unsubstantiated)
documentation for the same article through the real gap-analysis path
(analyse_article, same LangGraph chain used in production) and asserts the
score lands in the expected band.

Each document is written for exactly one domain, so it doubles as a free
deterministic check: the OTHER article should score exactly 0 (the
gap_analyser.py "no chunks classified" fallback), no LLM call needed.

Bands are intentionally generous (not narrow point targets) because
temperature=0/seed=42 determinism holds within a single Ollama process but
score drift of ~5-10 points has been observed across repeated real runs
(hardware/embedding-cache timing affects which passages get retrieved,
which affects what the LLM sees). The goal is to catch gross miscalibration
(a vague document scoring "excellent" or vice versa), not to pin an exact
number.

Requires: Ollama (phi3:mini) + ChromaDB running.

Usage:
    python tests/evaluation/eval_score_calibration.py
    python tests/evaluation/eval_score_calibration.py --verbose
"""

from __future__ import annotations

import argparse
import asyncio
import json
import sys
from pathlib import Path

REPO_ROOT   = Path(__file__).resolve().parent.parent.parent
RESULTS_DIR = Path(__file__).parent / "results"
RESULTS_DIR.mkdir(exist_ok=True)
_API_DIR = next((p for p in [REPO_ROOT / "api", Path("/app")] if p.is_dir()), Path("/app"))
sys.path.insert(0, str(_API_DIR))

# ── Calibration cases ─────────────────────────────────────────────────────────
# Each case: one document written for exactly one article/domain.
# expected_min/max bound the score for THAT article; the other article in
# each pair (see CASES grouping below) should score exactly 0 (no chunks).

_STRONG_RISK_DOC = """
Risk Management Programme

Our AI-based credit scoring system is governed by a documented risk management
system established and maintained throughout its lifecycle, per our internal
AI governance standard. Risks are identified using a structured FMEA
methodology, run quarterly by the model risk committee, covering known and
reasonably foreseeable risks including demographic bias, data drift, and
adversarial manipulation. Each identified risk is assigned a residual risk
score after mitigation, and mitigation measures (retraining triggers,
fairness constraints, input validation) are tracked to closure in our risk
register. Testing against the identified risks is conducted before every
model release, with results reviewed by an independent validation team.
Post-deployment monitoring continuously feeds new risk signals back into the
risk register, closing the loop across the entire system lifecycle.
"""

_WEAK_RISK_DOC = """
Risk Management

We try to think about risks with our AI system when we have time. Sometimes
we notice something might be a problem and we talk about it as a team.
"""

_STRONG_TRANSPARENCY_DOC = """
Transparency and User Disclosure

Every user interacting with our automated recommendation system is shown a
clear, prominent notice at first contact stating that decisions are
generated by an AI system, not a human. The notice explains, in plain
language, what the system does, its known limitations (e.g. reduced accuracy
for underrepresented demographic groups, documented in our published model
card), and provides a direct contact channel to request human review of any
decision within 5 business days. Instructions for use are published publicly
and versioned alongside each model release, and include worked examples of
how to interpret the system's confidence scores.
"""

_WEAK_TRANSPARENCY_DOC = """
Transparency

Users are told about the AI sometimes if they ask.
"""

# (source_file_label, doc_text, target_domain, target_article, expect_min, expect_max, other_article)
CASES = [
    ("strong_risk",          _STRONG_RISK_DOC,          "risk_management", 9,  55, 100, 13),
    ("weak_risk",            _WEAK_RISK_DOC,             "risk_management", 9,  0,  45, None),
    ("strong_transparency",  _STRONG_TRANSPARENCY_DOC,   "transparency",    13, 55, 100, 9),
    ("weak_transparency",    _WEAK_TRANSPARENCY_DOC,     "transparency",    13, 0,  45, None),
]


async def _run_async(verbose: bool) -> dict:
    import os

    try:
        from services.chunker           import proposition_chunk_text
        from services.language_detector import detect_language
        from services.classifier        import classify_chunks
        from services.embedding_service import EmbeddingService
        from services.chroma_client     import ChromaClient
        from services.rag_engine        import retrieve_requirements, build_bm25_index, select_query_chunks
        from services.gap_analyser      import analyse_article
        from services.ollama_client     import OllamaClient
        from models.schemas             import ArticleDomain
    except ImportError as e:
        return _skip(f"Cannot import API services: {e}")

    ollama_host  = os.getenv("OLLAMA_HOST",  "localhost")
    chroma_host  = os.getenv("CHROMADB_HOST", "localhost")
    ollama_model = os.getenv("OLLAMA_MODEL",  "phi3:mini")

    ollama = OllamaClient(host=ollama_host, model=ollama_model)
    chroma = ChromaClient(host=chroma_host)
    try:
        ok = await ollama.health_check() and await chroma.health_check()
        if not ok:
            raise RuntimeError()
    except Exception as e:
        return _skip(f"Ollama or ChromaDB not reachable: {e}")

    emb = EmbeddingService()
    await build_bm25_index(chroma)

    DOMAIN_BY_LABEL = {
        "risk_management": ArticleDomain.RISK_MANAGEMENT,
        "transparency":    ArticleDomain.TRANSPARENCY,
    }

    case_results: list[dict] = []
    violations: list[str] = []

    for label, doc_text, domain_label, article_num, exp_min, exp_max, other_article in CASES:
        domain = DOMAIN_BY_LABEL[domain_label]

        chunks = await proposition_chunk_text(doc_text, source_file=f"{label}.txt")
        lang = await detect_language(doc_text)
        for c in chunks:
            c.language = lang
        chunks, _backend = await classify_chunks(chunks, ollama)

        domain_chunks = [c for c in chunks if c.domain == domain]

        passages: list[dict] = []
        query_chunks = await select_query_chunks(domain_chunks, article_num, emb) if domain_chunks else []
        for c in query_chunks:
            try:
                retrieved = await retrieve_requirements(
                    chunk=c, embedding_service=emb, chroma_client=chroma,
                    top_k=5, regulation="eu_ai_act",
                )
                passages.extend(retrieved)
            except Exception:
                pass

        score = await analyse_article(
            article_num=article_num, domain=domain, user_chunks=domain_chunks,
            regulatory_passages=passages, ollama=ollama, applicable_articles=None,
        )

        in_band = exp_min <= score.score <= exp_max
        if not in_band:
            violations.append(
                f"{label}: Article {article_num} scored {score.score}, "
                f"expected [{exp_min}, {exp_max}]"
            )

        entry = {
            "case":           label,
            "article_num":    article_num,
            "domain_chunks":  len(domain_chunks),
            "passages":       len(passages),
            "score":          score.score,
            "expected_min":   exp_min,
            "expected_max":   exp_max,
            "in_band":        in_band,
        }

        # Free deterministic check: the OTHER article should score exactly 0
        # since this document has zero chunks for it (gap_analyser.py's
        # "no chunks classified" fallback — no LLM call involved).
        if other_article is not None:
            other_domain_chunks = [c for c in chunks if c.domain != domain and c.domain is not None]
            # This document should have no chunks classified to any domain
            # besides the one it was written for.
            zero_check_ok = len([c for c in chunks if c.domain and c.domain != domain]) == 0
            entry["other_article"] = other_article
            entry["other_article_zero_check_ok"] = zero_check_ok
            if not zero_check_ok:
                violations.append(
                    f"{label}: expected no chunks classified outside {domain_label}, "
                    f"but found {len(other_domain_chunks)} chunk(s) in other domains"
                )

        case_results.append(entry)

        if verbose:
            icon = "✓" if in_band else "✗"
            print(f"  {icon} {label}: Article {article_num} = {score.score}  "
                  f"(expected [{exp_min}, {exp_max}])  chunks={len(domain_chunks)} passages={len(passages)}")

    n_in_band = sum(1 for c in case_results if c["in_band"])
    calibration_rate = round(n_in_band / len(case_results), 4) if case_results else 0.0

    status = "pass" if not violations else ("warn" if calibration_rate >= 0.5 else "fail")

    results = {
        "eval":              "score_calibration",
        "status":            status,
        "calibration_rate":  calibration_rate,
        "n_cases":           len(case_results),
        "n_in_band":         n_in_band,
        "violations":        violations,
        "case_results":      case_results,
        "threshold_calibration_rate": 1.0,
    }

    out_path = RESULTS_DIR / "score_calibration.json"
    out_path.write_text(json.dumps(results, indent=2), encoding="utf-8")
    return results


def run(verbose: bool = False) -> dict:
    return asyncio.run(_run_async(verbose=verbose))


def _skip(reason: str) -> dict:
    return {"eval": "score_calibration", "status": "skip", "reason": reason}


def print_report(r: dict) -> None:
    if r["status"] == "skip":
        print(f"  [SKIP] {r['reason']}")
        return

    status_icon = "✓" if r["status"] == "pass" else ("!" if r["status"] == "warn" else "✗")
    print(f"\n  {'─'*52}")
    print(f"  {status_icon} Score Calibration")
    print(f"  {'─'*52}")
    print(f"  Calibration rate : {r['calibration_rate']*100:.1f}%  ({r['n_in_band']}/{r['n_cases']} in expected band)")

    if r["violations"]:
        print("\n  Violations:")
        for v in r["violations"]:
            print(f"    ✗ {v}")

    print("\n  Per-case:")
    for c in r.get("case_results", []):
        icon = "✓" if c["in_band"] else "✗"
        print(f"    {icon} {c['case']}: Article {c['article_num']} = {c['score']}  "
              f"(expected [{c['expected_min']}, {c['expected_max']}])")


# ── pytest ──────────────────────────────────────────────────────────────────

def test_score_calibration() -> None:
    """pytest: strong/weak documentation must score in the expected band."""
    r = run()
    if r["status"] == "skip":
        import pytest
        pytest.skip(r.get("reason", ""))
    assert not r["violations"], "Score calibration failures:\n" + "\n".join(r["violations"])


# ── CLI ─────────────────────────────────────────────────────────────────────

if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Score calibration evaluation")
    parser.add_argument("--verbose", "-v", action="store_true")
    args = parser.parse_args()

    print("Running score calibration evaluation …")
    results = run(verbose=args.verbose)
    print_report(results)
    sys.exit(0 if results.get("status") in ("pass", "warn") else 1)
